ok = bad = 0; cache = {}
for k, q in Q:
    f = os.path.join(P, "fulltext", k + ".txt")
    if not os.path.exists(f): print("NOFILE", k); bad += 1; continue
    if k not in cache:
        raw = open(f, errors="ignore").read()
        # two-column PDFs: also search left-column and right-column streams (segments split on 3+ spaces)
        L, R = [], []
        for line in raw.split("\n"):
            segs = [x for x in re.split(r"\s{3,}", line.strip()) if x]
            if segs: L.append(segs[0]); R.extend(segs[1:])
            if len(segs) == 1: R.append(segs[0])
        cache[k] = [norm(raw), norm("\n".join(L)), norm("\n".join(R))]
    nq = norm(q)
    hit = any(nq in t or nq.replace(" ", "") in t.replace(" ", "") for t in cache[k])
    if hit: ok += 1
    else: bad += 1; print("MISS", k, "|", q)
print(f"verified {ok}/{ok+bad}")
